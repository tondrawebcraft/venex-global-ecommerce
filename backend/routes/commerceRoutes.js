import { Router } from 'express';
import { body } from 'express-validator';
import * as commerce from '../controllers/commerceController.js';
import { protect, optionalAuth } from '../middleware/auth.js';
const router = Router();
const addressFields = [body('shippingAddress.fullName').trim().isLength({ min: 2, max: 100 }), body('shippingAddress.email').optional().isEmail(), body('shippingAddress.phone').trim().isLength({ min: 6, max: 30 }), body('shippingAddress.line1').trim().isLength({ min: 5, max: 200 }), body('shippingAddress.city').trim().isLength({ min: 2, max: 80 }), body('shippingAddress.district').trim().isLength({ min: 2, max: 80 }), body('paymentMethod').isIn(['cod', 'bkash', 'nagad', 'sslcommerz'])];
router.get('/cart', optionalAuth, commerce.readCart);
router.post('/cart/items', optionalAuth, body('productId').isMongoId(), body('quantity').optional().isInt({ min: 1, max: 50 }), commerce.addToCart);
router.patch('/cart/items/:itemId', optionalAuth, body('quantity').isInt({ min: 0, max: 50 }), commerce.updateCartItem);
router.delete('/cart/items/:itemId', optionalAuth, commerce.removeCartItem);
router.post('/cart/coupon', optionalAuth, body('code').trim().isLength({ min: 2, max: 40 }), commerce.applyCoupon);
router.delete('/cart/coupon', optionalAuth, commerce.removeCoupon);
router.get('/wishlist', optionalAuth, commerce.readWishlist);
router.post('/wishlist/:productId', optionalAuth, commerce.toggleWishlist);
router.post('/orders', optionalAuth, addressFields, commerce.createOrder);
router.get('/orders', protect, commerce.myOrders);
router.get('/orders/track/:orderNumber', commerce.orderTracking);
router.get('/orders/:id', protect, commerce.getOrder);
router.post('/orders/:id/cancel', protect, commerce.cancelOrder);
router.get('/addresses', protect, commerce.listAddresses);
router.post('/addresses', protect, body('fullName').trim().isLength({ min: 2 }), body('phone').trim().isLength({ min: 6 }), body('line1').trim().isLength({ min: 5 }), body('city').trim().isLength({ min: 2 }), body('district').trim().isLength({ min: 2 }), commerce.saveAddress);
router.delete('/addresses/:id', protect, commerce.deleteAddress);
router.post('/coupons/preview', body('code').trim().isLength({ min: 2 }), commerce.couponPreview);
router.get('/payments/callback/:provider', commerce.paymentCallback);
router.post('/payments/callback/:provider', commerce.paymentCallback);
router.get('/payments/orders/:orderId', protect, commerce.paymentTransactions);
router.post('/newsletter', body('email').isEmail().normalizeEmail(), commerce.subscribe);
router.post('/contact', commerce.contactMessage);
export default router;

